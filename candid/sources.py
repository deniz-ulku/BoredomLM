"""Training prompt sources.

Only prompts are taken from public datasets (plus one off-policy preference set for
image hallucination). Every answer used for training is generated by the base model
itself, see candid/generate.py.

Hub dataset names move from time to time, so each bucket lists fallbacks; the first
one that loads is used and the choice is logged.
"""

from __future__ import annotations

import itertools
import logging
from collections.abc import Callable, Iterator

from candid.config import Config
from candid.filters import detect_lang, is_hard_limit

log = logging.getLogger("candid.sources")

Row = dict  # {"id", "bucket", "lang", "prompt", "image"}


def _stream(name: str, config: str | None = None, split: str = "train"):
    from datasets import load_dataset

    return load_dataset(name, config, split=split, streaming=True)


TEXT_BUFFER = 10_000
# The shuffle buffer is one Arrow table; large images overflow its 2 GB binary offsets.
IMAGE_BUFFER = 200


def _first_working(cands: list[tuple[str, str | None, str, Callable]], seed: int,
                   buffer: int = TEXT_BUFFER) -> Iterator[Row]:
    last_err = None
    for name, config, split, fn in cands:
        try:
            ds = _stream(name, config, split).shuffle(seed=seed, buffer_size=buffer)
            it = iter(ds)
            first = next(it)  # fail here, not later, if the source is broken
            log.info("using %s (%s/%s)", name, config, split)
            return (row for ex in itertools.chain([first], it) for row in fn(ex))
        except Exception as e:  # noqa: BLE001 - try the next candidate
            last_err = e
            log.warning("could not load %s (%s): %s", name, config, e)
    raise RuntimeError(f"no source loaded; last error: {last_err}")


def _take(it: Iterator[Row], n: int, bucket: str, keep: Callable[[Row], bool] = lambda r: True) -> list[Row]:
    out, seen = [], set()
    for r in it:
        if len(out) >= n:
            break
        p = (r.get("prompt") or "").strip()
        if not p or len(p) > 6000 or p in seen or not keep(r):
            continue
        seen.add(p)
        r["prompt"] = p
        r["bucket"] = bucket
        r["id"] = f"{bucket}-{len(out)}"
        r.setdefault("image", None)
        r.setdefault("lang", detect_lang(p))
        out.append(r)
    if len(out) < n:
        log.warning("%s: wanted %d prompts, got %d", bucket, n, len(out))
    return out


# ----- per-source row mappers -------------------------------------------------

def _first_user(messages) -> str | None:
    for m in messages or []:
        if m.get("role") == "user":
            c = m.get("content")
            return c if isinstance(c, str) else None
    return None


def _map_messages(ex):
    p = _first_user(ex.get("messages") or ex.get("conversations"))
    if p:
        yield {"prompt": p}


def _map_aya(ex):
    if (ex.get("language") or "").lower() in ("turkish", "tur", "tr"):
        yield {"prompt": ex.get("inputs"), "lang": "tr"}


def _map_tr_messages(ex):
    p = _first_user(ex.get("messages") or ex.get("conversations"))
    if p and detect_lang(p) == "tr":
        yield {"prompt": p, "lang": "tr"}


def _map_orbench(ex):
    yield {"prompt": ex.get("prompt"), "category": ex.get("category")}


def _map_cauldron(ex):
    imgs, texts = ex.get("images") or [], ex.get("texts") or []
    if len(imgs) == 1 and texts:
        yield {"prompt": texts[0].get("user"), "image": imgs[0]}


GENERAL_EN = [
    ("HuggingFaceTB/smoltalk", "all", "train", _map_messages),
    ("HuggingFaceH4/ultrachat_200k", None, "train_sft", _map_messages),
]
GENERAL_TR = [
    ("CohereLabs/aya_dataset", None, "train", _map_aya),
    ("CohereForAI/aya_dataset", None, "train", _map_aya),
    ("HuggingFaceTB/smoltalk2", "SFT", "train", _map_tr_messages),
]
OVER_REFUSAL = [
    ("bench-llm/or-bench", "or-bench-80k", "train", _map_orbench),
]
TOXIC = [
    ("bench-llm/or-bench", "or-bench-toxic", "train", _map_orbench),
]
CAULDRON_SUBSETS = ["docvqa", "chartqa", "textvqa", "ai2d", "infographic_vqa", "vqav2", "aokvqa", "screen2words"]


def _image_prompts(n: int, seed: int) -> list[Row]:
    per = max(1, n // len(CAULDRON_SUBSETS))
    out: list[Row] = []
    for sub in CAULDRON_SUBSETS:
        try:
            it = _first_working([("HuggingFaceM4/the_cauldron", sub, "train", _map_cauldron)], seed, IMAGE_BUFFER)
            out += _take(it, per, "image")
        except RuntimeError as e:
            log.warning("skipping cauldron/%s: %s", sub, e)
    for i, r in enumerate(out):
        r["id"] = f"image-{i}"
    return out


def _eval_prompts() -> set[str]:
    """OR-Bench-Hard-1k is the over-refusal eval set; keep it out of training."""
    try:
        from datasets import load_dataset

        ds = load_dataset("bench-llm/or-bench", "or-bench-hard-1k", split="train")
        return {ex["prompt"].strip() for ex in ds}
    except Exception as e:  # noqa: BLE001
        log.warning("could not load held-out eval prompts: %s", e)
        return set()


def build_prompts(cfg: Config) -> list[Row]:
    s = cfg.seed
    not_hard = lambda r: not is_hard_limit(r["prompt"])
    held_out = _eval_prompts()
    rows = []
    rows += _take(_first_working(GENERAL_EN, s), cfg.n_general_en, "general_en", not_hard)
    rows += _take(_first_working(GENERAL_TR, s), cfg.n_general_tr, "general_tr", not_hard)
    rows += _take(_first_working(OVER_REFUSAL, s), cfg.n_over_refusal, "over_refusal",
                  lambda r: not_hard(r) and r["prompt"] not in held_out)
    rows += _take(_first_working(TOXIC, s), cfg.n_hard_limit, "hard_limit", lambda r: is_hard_limit(r["prompt"]))
    rows += _image_prompts(cfg.n_image, s)
    return rows


def image_preference_pairs(cfg: Config) -> list[dict]:
    """RLAIF-V: human/AI-labelled pairs where the rejected answer describes things not in the image."""
    def m(ex):
        if ex.get("image") is not None and ex.get("chosen") and ex.get("rejected"):
            yield {"prompt": ex.get("question"), "image": ex["image"],
                   "chosen": ex["chosen"], "rejected": ex["rejected"]}

    it = _first_working([("openbmb/RLAIF-V-Dataset", None, "train", m)], cfg.seed, IMAGE_BUFFER)
    rows = _take(it, cfg.n_image_pref, "image_pref")
    return rows
